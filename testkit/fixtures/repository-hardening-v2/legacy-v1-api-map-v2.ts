export interface LegacyV1ApiReplacementV2 {
  readonly legacy: string;
  readonly replacement: string | null;
  readonly disposition: 'replace' | 'removed-internal-only' | 'retained-root';
}

export type LegacyV1SourceStateV2 = 'present' | 'removed';

/** Fixture-owned phase state; C5 flips this when the legacy source is removed. */
export const LEGACY_V1_SOURCE_STATE_V2: LegacyV1SourceStateV2 = 'present';

/** Public compatibility rows that are not transitive exports of legacy-v1.ts. */
export const LEGACY_V1_NON_SUBPATH_API_KEYS_V2 = Object.freeze([
  'repo-nav/legacy-v1',
  'repo-nav/advanced',
  'repo-nav/backends',
  'repo-nav/node',
  'CodeGraphBackend.probe',
  'CodeGraphBackend.search',
  'PackageMetadataV1',
  'RipgrepBackend.probe',
  'RipgrepBackend.search',
] as const);

function replace(
  legacy: string,
  replacement: string,
): LegacyV1ApiReplacementV2 {
  return Object.freeze({ legacy, replacement, disposition: 'replace' });
}

function removed(legacy: string): LegacyV1ApiReplacementV2 {
  return Object.freeze({
    legacy,
    replacement: null,
    disposition: 'removed-internal-only',
  });
}

function retained(
  legacy: string,
  replacement: string,
): LegacyV1ApiReplacementV2 {
  return Object.freeze({ legacy, replacement, disposition: 'retained-root' });
}

